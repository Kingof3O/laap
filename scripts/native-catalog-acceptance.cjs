const fs = require('node:fs/promises');
const assert = require('node:assert/strict');
const { NativeDriver } = require('./native-driver.cjs');

async function main() {
  const session = JSON.parse(await fs.readFile(process.argv[2] ?? '.artifacts/native-acceptance/studio-session.json', 'utf8')).value;
  const driver = new NativeDriver(session.sessionId, process.env.LAAP_NATIVE_DRIVER_URL);
  const checks = [];
  const passed = name => { checks.push(name); console.log(`PASS native: ${name}`); };
  await driver.click('Catalog'); await driver.wait('Search champions');
  await driver.clickXpath('//button[strong[normalize-space(.)="Ahri"]]');
  await driver.wait('Create preset');
  await driver.click('Create preset');
  const name = 'Native catalog preference ' + Date.now();
  await driver.type('Preset name', name);
  await driver.clickXpath('//label[contains(.,"Queue preference")]/select/option[normalize-space(.)="classic"]');
  await driver.click('Save preset'); await driver.wait('Saved presets'); await driver.wait(name);
  const saved = (await driver.invoke('customization_preset_list')).find(p => p.name === name);
  assert(saved); assert.equal(saved.accountId, null); assert.equal(saved.queueMode, 'classic');
  passed('Real cached/public catalog → champion → cosmetic reference → native global preset');
  const row = `//li[.//strong[normalize-space(.)=${JSON.stringify(name)}]]`;
  await driver.clickXpath(row + '//button[normalize-space(.)="Edit"]');
  await driver.type('Notes', 'Independent native catalog preference');
  await driver.type('Priority', '7'); await driver.click('Save preset');
  await driver.click('Overview'); await driver.click('Presets'); await driver.wait(name);
  const edited = (await driver.invoke('customization_preset_list')).find(p => p.id === saved.id);
  assert.equal(edited.notes, 'Independent native catalog preference'); assert.equal(edited.priority, 7);
  passed('Edit → leave → reopen preserves preset identity, priority and notes');
  await driver.clickXpath(row + '//button[normalize-space(.)="Duplicate"]');
  await driver.wait('Duplicated preset');
  const duplicate = (await driver.invoke('customization_preset_list')).find(p => p.id !== saved.id && p.name.includes(name));
  assert(duplicate);
  const duplicateRow = `//li[.//strong[normalize-space(.)=${JSON.stringify(duplicate.name)}]]`;
  await driver.clickXpath(duplicateRow + '//button[normalize-space(.)="Delete"]');
  await driver.clickXpath(duplicateRow + '//button[normalize-space(.)="Confirm delete"]');
  await driver.wait('Restore preset'); await driver.click('Restore preset'); await driver.wait('Restored preset from trash.');
  assert((await driver.invoke('customization_preset_list')).some(p => p.id === duplicate.id));
  passed('Native duplication → confirmed deletion → trash restoration preserves the copied preset');
  const portable = await driver.invoke('customization_preset_export');
  await fs.writeFile('.artifacts/native-acceptance/original-presets.json', portable);
  const before = (await driver.invoke('customization_preset_list')).length;
  await driver.upload('//label[contains(.,"Import presets")]//input', '.artifacts/native-acceptance/original-presets.json');
  await driver.wait('Confirm import'); await driver.click('Confirm import'); await driver.wait('Local profile links can be assigned');
  const after = await driver.invoke('customization_preset_list'); assert(after.length > before);
  assert(after.every(p => p.accountId === null));
  passed('Native JSON export → GUI preview → confirmed import creates independent global copies');
  await driver.screenshot('.artifacts/native-acceptance/presets-native.png');
  await fs.writeFile('.artifacts/native-acceptance/native-catalog-result.json', JSON.stringify({ type: 'native WebView2 UI with real catalog and persistence IPC', platform: 'Windows', mocked: false, checks, passed: checks.length, failed: 0, limitations: ['Cosmetic metadata preferences do not equip or unlock League cosmetics.', 'Complete account-linked switching is covered separately by Rust tests, not this Studio journey.'] }, null, 2));
}
main().catch(error => { console.error(error); process.exitCode = 1; });
